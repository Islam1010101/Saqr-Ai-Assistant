import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { createClient } from "npm:@supabase/supabase-js@2.58.0";
const allowed = (origin:string|null) => !!origin && (origin === "https://www.efipslibrary.com" || origin === "https://efipslibrary.com" || /^https:\/\/[a-z0-9-]+\.vercel\.app$/.test(origin));
Deno.serve(async(req:Request)=>{
 const origin=req.headers.get("origin");
 const headers:Record<string,string>={"Access-Control-Allow-Headers":"authorization, apikey, x-client-info, content-type","Access-Control-Allow-Methods":"POST,OPTIONS","Vary":"Origin"};
 if(allowed(origin))headers["Access-Control-Allow-Origin"]=origin!;
 const reply=(status:number,body:Record<string,unknown>)=>new Response(JSON.stringify(body),{status,headers:{...headers,"Content-Type":"application/json","Cache-Control":"no-store"}});
 if(req.method==="OPTIONS")return new Response(null,{status:allowed(origin)?204:403,headers});
 if(req.method!=="POST")return reply(405,{code:"METHOD_NOT_ALLOWED"});
 if(!allowed(origin))return reply(403,{code:"ORIGIN_NOT_ALLOWED"});
 const token=req.headers.get("authorization")?.match(/^Bearer\s+(.+)$/i)?.[1];
 if(!token)return reply(401,{code:"AUTH_REQUIRED"});
 const url=Deno.env.get("SUPABASE_URL"),anon=Deno.env.get("SUPABASE_ANON_KEY"),secret=Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
 if(!url||!anon||!secret)return reply(503,{code:"SERVER_UNAVAILABLE"});
 const client=createClient(url,anon,{auth:{persistSession:false,autoRefreshToken:false}});
 const {data:{user},error}=await client.auth.getUser(token);
 if(error||!user?.id||!user.email||!user.email_confirmed_at)return reply(401,{code:"AUTH_INVALID"});
 const email=user.email.toLowerCase().trim();
 if(!/^[^@\s]+@falcon-school\.com$/.test(email))return reply(403,{code:"SCHOOL_EMAIL_REQUIRED"});
 if(!(user.identities||[]).some(i=>i.provider==="google" && String(i.identity_data?.email||"").trim().toLowerCase()===email && i.identity_data?.email_verified===true))return reply(403,{code:"GOOGLE_REQUIRED"});
 const admin=createClient(url,secret,{auth:{persistSession:false,autoRefreshToken:false}});
 const {data:entry,error:lookupError}=await admin.from("efips_google_staff_accounts").select("teacher_id,role").eq("email",email).maybeSingle();
 if(lookupError)return reply(503,{code:"ROSTER_UNAVAILABLE"});
 if(!entry)return reply(403,{code:"EMAIL_NOT_AUTHORIZED"});
 const {data:teacher,error:teacherError}=await admin.from("teachers").select("id,teacher_id,name_ar,name_en,created_at").eq("teacher_id",entry.teacher_id).maybeSingle();
 if(teacherError||!teacher)return reply(403,{code:"STAFF_NOT_FOUND"});
 const role=entry.role==="admin" && entry.teacher_id==="HR785" ? "admin" : "teacher";
 const audit=await admin.from("login_logs").insert([{user_id:teacher.teacher_id,user_type:role}]);if(audit.error)console.error("Teacher login audit unavailable");
 return reply(200,{profile:teacher,role});
});